test('dialog ponsel menjaga fokus dan kembali ke pemicunya', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/#/materi/mod-1')
  const search = page.getByRole('button', { name: 'Cari materi biologi (Ctrl K)' })
  await search.click()
  await expect(page.getByRole('searchbox', { name: 'Materi atau subtopik' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(search).toBeFocused()
  const menu = page.getByRole('button', { name: 'Buka menu navigasi' })
  await menu.click()
  await expect(page.getByRole('dialog', { name: 'Menu belajar' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(menu).toBeFocused()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
})

test('PWA menjaga kuis offline dan memberi pemulihan atlas yang jelas', async ({ page, context }) => {
  await page.goto('/')
  await page.evaluate(() => navigator.serviceWorker.ready)
  await expect.poll(() => page.evaluate(() => Boolean(navigator.serviceWorker.controller))).toBe(true)
  await context.setOffline(true)
  await page.goto('/#/anatomi')
  await expect(page.getByRole('heading', { name: 'Atlas memerlukan koneksi internet' })).toBeVisible()
  await expect(page.locator('iframe')).toHaveCount(0)
  await page.getByRole('button', { name: 'Coba lagi' }).click()
  await expect(page.getByRole('status')).toContainText('Koneksi belum tersedia')
  await context.setOffline(false)
  await expect(page.locator('iframe')).toBeVisible()
  await expect(page.getByRole('status')).toBeEmpty()
  await expect.poll(async () => {
    const frame = page.frames().find(item => item.url().includes('/human-atlas/'))
    return frame ? frame.title() : ''
  }).toBe('Human Atlas')
  await context.setOffline(true)
  await expect(page.locator('iframe')).toHaveCount(0)
  await page.getByRole('link', { name: 'Buka materi biologi' }).click()
  await expect(page.getByRole('heading', { name: 'Katalog Materi' })).toBeVisible()
  await page.goto('/#/kuis?quizId=quiz-sel')
  await expect(page.getByRole('radio')).toHaveCount(4)
})
