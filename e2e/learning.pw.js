import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'

const materials = JSON.parse(readFileSync(new URL('../src/data/materiData.json', import.meta.url)))
const quizzes = JSON.parse(readFileSync(new URL('../src/data/quizData.json', import.meta.url)))

test.beforeEach(async ({ page }) => {
  await page.route(/^https:\/\/fonts\.(googleapis|gstatic)\.com\//, route => route.abort())
})

test('kuis diagram dan zoom direset ketika diagram berganti', async ({ page }) => {
  await page.goto('/#/materi/mod-1')
  await page.getByRole('button', { name: 'Kenali Bagian', exact: true }).click()
  await expect(page.locator('.question-progress')).toContainText('1 dari 4')
  await page.getByRole('button', { name: 'Perbesar Diagram', exact: true }).click()
  await page.getByRole('button', { name: '6 Pembelahan Sel (Mitosis & Meiosis)', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Eksplorasi', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.question-target')).toHaveCount(0)
  await expect(page.locator('.react-transform-component')).toHaveCSS('transform', /matrix\(1, 0, 0, 1,/)
  await page.getByRole('button', { name: 'Kenali Bagian', exact: true }).click()
  const diagram = materials.modules[0].subtopics[5].content.find(block => block.type === 'interactiveImage')
  const target = (await page.locator('.question-target').textContent()).replaceAll('"', '')
  const targetIndex = diagram.parts.findIndex(part => part.label === target)
  expect(targetIndex).toBeGreaterThanOrEqual(0)
  await expect(page.locator('.question-progress')).toContainText('1 dari 5')
  await page.getByRole('button', { name: `Pilih area nomor ${targetIndex + 1}`, exact: true }).click()
  await expect(page.locator('.feedback-card')).toContainText('Benar!')
})

test('radio, keyboard, fokus soal, hasil, dan ulang kuis bekerja bersama', async ({ page }) => {
  await page.goto('/#/kuis?quizId=quiz-sel')
  const quiz = quizzes.quizzes.find(item => item.id === 'quiz-sel')
  const heading = page.locator('.quiz-engine-card h3')
  await expect(heading).toBeFocused()
  const radios = page.getByRole('radio')
  await radios.first().focus()
  await page.keyboard.press('Space')
  await expect(radios.first()).toBeChecked()
  await page.keyboard.press('ArrowDown')
  await expect(radios.nth(1)).toBeChecked()
  await expect(radios.first()).not.toBeChecked()
  await page.getByRole('button', { name: 'Selanjutnya' }).click()
  await expect(heading).toBeFocused()
  await expect(heading).toHaveText(quiz.questions[1].question)
  await page.getByRole('button', { name: 'Sebelumnya' }).click()
  await expect(heading).toBeFocused()
  await expect(radios.nth(1)).toBeChecked()
  for (const [index, question] of quiz.questions.entries()) {
    await radios.nth(question.correctIndex).check()
    if (index < quiz.questions.length - 1) {
      await page.getByRole('button', { name: 'Selanjutnya' }).click()
      await expect(heading).toBeFocused()
    }
  }
  await page.getByRole('button', { name: 'Kirim Jawaban' }).click()
  await expect(page.getByRole('heading', { name: 'Hasil kuis: 100 dari 100' })).toBeFocused()
  await page.getByRole('button', { name: 'Ulangi Kuis Formatif' }).click()
  await expect(heading).toBeFocused()
  await expect(page.locator('input[type="radio"]:checked')).toHaveCount(0)
})

test('glosarium dapat dibuka dan ditutup dengan keyboard', async ({ page }) => {
  await page.goto('/#/materi/mod-1')
  const term = page.locator('.glossary-term').first()
  await expect(term).toHaveAttribute('aria-expanded', 'false')
  await term.focus()
  await page.keyboard.press('Enter')
  await expect(term).toHaveAttribute('aria-expanded', 'true')
  const definition = page.locator('.glossary-definition').first()
  await expect(definition).toBeVisible()
  await expect(term).toHaveAttribute('aria-describedby', await definition.getAttribute('id'))
  await page.keyboard.press('Space')
  await expect(definition).toBeHidden()
})

